function seededFraction(index: number, salt: number): number {
  const x = Math.sin((index + 1) * 9973 + salt * 7919) * 10000;
  return x - Math.floor(x);
}

function padRecordTime(baseDay: number, hour: number, minute: number, second: number): string {
  const day = String(baseDay).padStart(2, '0');
  const hh = String(hour).padStart(2, '0');
  const mm = String(minute).padStart(2, '0');
  const ss = String(second).padStart(2, '0');
  return `2026-07-${day} ${hh}:${mm}:${ss}`;
}

function buildTeamApiId(index: number): string {
  return `TA-${String(10001 + index).padStart(5, '0')}`;
}

function buildApiKeyMasked(index: number): string {
  const prefix = seededFraction(index, 3).toString(36).slice(2, 5);
  return `ak_${prefix}*******************...`;
}

function buildApiKeyFull(index: number): string {
  const suffix = seededFraction(index, 7).toString(36).slice(2, 18);
  return `ak_${String(index).padStart(2, '0')}${suffix}`;
}

function buildAutoGeneratedApiName(index: number): string {
  if (index < TEAM_API_NAME_POOL.length) {
    return TEAM_API_NAME_POOL[index]!;
  }
  const base = TEAM_API_NAME_POOL[index % TEAM_API_NAME_POOL.length]!;
  return `${base} #${index - TEAM_API_NAME_POOL.length + 2}`;
}

function resolveCreator(index: number): { name: string; email: string } {
  const poolIndex = Math.floor(seededFraction(index, 19) * CREATOR_POOL.length);
  return CREATOR_POOL[poolIndex % CREATOR_POOL.length]!;
}

export function buildInitialTeamApiConfigs(): TeamApiConfigRecord[] {
  return Array.from({ length: TEAM_API_MOCK_ROW_COUNT }, (_, index) => {
    const creator = resolveCreator(index);
    const day = 13 - Math.floor(index / 4);
    const hour = 14 - (index % 6);
    const minute = 30 + (index % 28);
    const enabled = index !== 0 && index !== 2;

    return {
      id: buildTeamApiId(index),
      name: buildAutoGeneratedApiName(index),
      authType: 'HMAC',
      apiKeyMasked: buildApiKeyMasked(index),
      apiKeyFull: buildApiKeyFull(index),
      secretKey: `sk_${String(index).padStart(2, '0')}_hmac_${seededFraction(index, 11).toString(36).slice(2, 14)}`,
      baseUrl: 'https://api.cregis.com',
      permissionsKey: PERMISSION_KEYS[index % PERMISSION_KEYS.length]!,
      ipWhitelist: IP_WHITELIST_DEMO,
      creatorName: creator.name,
      creatorEmail: creator.email,
      createdAt: padRecordTime(Math.max(1, day), Math.max(0, hour), minute % 60, index % 60),
      enabled,
    };
  });
}
