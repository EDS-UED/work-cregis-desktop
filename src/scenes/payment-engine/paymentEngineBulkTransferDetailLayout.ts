export const BULK_TRANSFER_DETAIL_HASH_SENDER_COLUMN_MIN_WIDTH = '248px';
export const BULK_TRANSFER_DETAIL_STATUS_COLUMN_MIN_WIDTH = '145px';
export const BULK_TRANSFER_DETAIL_ONCHAIN_TIME_COLUMN_MIN_WIDTH = '200px';
